// A note paired with a blog page: saving the note rewrites only the page's
// article body; a hand edit to that body is caught before anything is
// overwritten; File > Open Blog Post... can create the page.

import { test, after, before } from 'node:test'
import assert from 'node:assert/strict'
import crypto from 'node:crypto'
import fs from 'node:fs'
import path from 'node:path'
import { startApp } from '../harness.mjs'

let t
let win

const sha256 = (text) => crypto.createHash('sha256').update(text, 'utf8').digest('hex')
const marked = (body) => `<!-- marktext:body:begin sha256=${sha256(body)} -->${body}<!-- marktext:body:end -->`
const bodyOf = (html) => html.match(/<!-- marktext:body:begin sha256=[0-9a-f]{64} -->([\s\S]*?)<!-- marktext:body:end -->/)?.[1]
const outsideBody = (html) => html.replace(/<!-- marktext:body:begin[\s\S]*?<!-- marktext:body:end -->/, '')

// A page shaped like a live post, with an SEO block and asset lines that
// must come through every save untouched.
const sitePage = (inner) => `<!DOCTYPE html>
<html lang="en">
<head>
    <meta charset="UTF-8">
    <title>Paired post - Thought Cloud</title>
    <!-- seo-meta:begin (auto-generated by scripts/build_seo.py — do not edit) -->
    <meta name="description" content="A hand-written description">
    <!-- seo-meta:end -->
    <link rel="stylesheet" href="../post.css?v=9.9">
    <script defer src="../footnotes.js?v=9"></script>
</head>
<body>
    <nav><span class="breadcrumb-current">Paired post</span></nav>
    <main class="content">
        <header class="article-header">
            <div class="post-meta-strip above" data-slug="paired-post"></div>
            <h1 class="article-title">Paired post</h1>
        </header>
        <div class="article-body">
            <div class="body markup" dir="auto">${inner}</div>
        </div>
    </main>
</body>
</html>`

const PAGE = 'site/thought-cloud/paired-post/index.html'
const pagePath = () => path.join(t.workspace, PAGE)
const readPage = () => fs.readFileSync(pagePath(), 'utf8')

const until = async (check, message, timeout = 15000) => {
  const start = Date.now()
  for (;;) {
    const value = await check()
    if (value) return value
    if (Date.now() - start > timeout) assert.fail(`Timed out waiting: ${message}`)
    await win.waitForTimeout(100)
  }
}

const blogPost = () => t.store('editor', (s) => s.currentFile && s.currentFile.blogPost && { ...s.currentFile.blogPost })

// What File > Save does: the menu asks the renderer for the current tab.
const save = () =>
  t.app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].webContents.send('mt::editor-ask-file-save'))

const openNote = async (relative) => {
  const file = path.join(t.workspace, relative)
  await win.evaluate((filePath) => window.electron.ipcRenderer.send('mt::open-file', filePath, {}), file)
  await until(
    () => t.store('editor', (s, p) => s.currentFile && s.currentFile.pathname === p, file),
    `${relative} open`
  )
  await win.waitForTimeout(400)
}

const appendToParagraph = async (text, extra) => {
  await t.caretAtEndOf(text)
  await t.type(extra)
  await until(
    () => t.store('editor', (s) => !s.currentFile.isSaved),
    'edit registered'
  )
}

before(async () => {
  t = await startApp({
    open: ['blog/paired.md'],
    files: {
      'blog/paired.md':
        '---\nblog_html: ../site/thought-cloud/paired-post/index.html\n---\n# Paired post\n\nFirst paragraph.\n\nSecond paragraph.\n',
      [PAGE]: sitePage(marked('<p>First paragraph.</p>\n<p>Second paragraph.</p>\n')),
      'blog/fresh.md': '# Fresh post\n\nBrand new text.\n',
      'site/thought-cloud/older-post/index.html':
        '<html>\n<head>\n    <link rel="stylesheet" href="../post.css?v=9.9">\n    <script defer src="../only-on-the-site.js?v=4"></script>\n</head>\n<body></body>\n</html>'
    }
  })
  win = t.win
})
after(() => t?.close())

test('opening a note that names its page pairs it', async () => {
  const state = await until(blogPost, 'tab paired')
  assert.equal(state.htmlPath, pagePath())
  assert.equal(state.held, false)
  assert.equal(state.revision, 0)
})

test('saving rewrites the page body and nothing else', async () => {
  const before = readPage()
  await appendToParagraph('Second paragraph.', ' Added in MarkText.')
  await save()
  await until(async () => (await blogPost()).revision === 1, 'page written')

  const after = readPage()
  assert.match(bodyOf(after), /Second paragraph\. Added in MarkText\./)
  assert.ok(!/<h1/.test(bodyOf(after)), 'the leading H1 is the title, not body')
  assert.equal(outsideBody(after), outsideBody(before), 'head, nav, header untouched')
  assert.equal(sha256(bodyOf(after)), after.match(/sha256=([0-9a-f]{64})/)[1])
})

test('a hand edit to the page body is caught and nothing is overwritten', async () => {
  const handEdited = readPage().replace('First paragraph.', 'First paragraph, fixed by hand.')
  fs.writeFileSync(pagePath(), handEdited)

  await appendToParagraph('First paragraph.', ' Another edit.')
  await save()
  await win.locator('[data-testid="blog-ask-title"]').waitFor({ state: 'visible' })
  assert.equal(readPage(), handEdited, 'page left as it was')
  assert.equal((await blogPost()).held, true)

  const changes = await win.locator('[data-testid="blog-diff"] .diff-block').allTextContents()
  assert.ok(changes.some((c) => /fixed by hand/.test(c) && /Another edit/.test(c)), changes.join('\n'))

  // Hold: later saves leave the page alone too.
  await win.locator('[data-testid="blog-ask-hold"]').click()
  await appendToParagraph('Another edit.', ' And more.')
  await save()
  await until(() => t.store('editor', (s) => s.currentFile.isSaved), 'note saved')
  await win.waitForTimeout(800)
  assert.equal(readPage(), handEdited, 'held: page still untouched')

  // Overwrite, from the Open Blog Post dialog where the choice stays visible.
  await t.app.evaluate(({ BrowserWindow }) =>
    BrowserWindow.getAllWindows()[0].webContents.send('mt::show-blog-post-dialog'))
  await win.locator('[data-testid="blog-resume"]').waitFor({ state: 'visible' })
  await win.locator('[data-testid="blog-overwrite-now"]').click()
  await until(async () => (await blogPost()).held === false, 'resumed after overwrite')
  const overwritten = readPage()
  assert.match(bodyOf(overwritten), /First paragraph\. Another edit\. And more\./)
  assert.ok(!overwritten.includes('fixed by hand'))
})

test('Create new .html builds the page and pairs the note', async () => {
  await openNote('blog/fresh.md')
  const newPage = path.join(t.workspace, 'site/thought-cloud/fresh-post/index.html')
  fs.mkdirSync(path.dirname(newPage), { recursive: true })
  // The asset lines come from the most recently changed sibling post; the
  // saves above made that paired-post, so touch the one this test looks for.
  const sibling = path.join(t.workspace, 'site/thought-cloud/older-post/index.html')
  fs.utimesSync(sibling, new Date(), new Date())
  await t.app.evaluate(({ dialog, BrowserWindow }, file) => {
    dialog.showSaveDialog = async () => ({ filePath: file, canceled: false })
    BrowserWindow.getAllWindows()[0].webContents.send('mt::show-blog-post-dialog')
  }, newPage)

  await win.locator('[data-testid="blog-create-page"]').click()
  await until(() => fs.existsSync(newPage), 'page created')
  await win.locator('[data-testid="blog-open-confirm"]').click()

  const html = fs.readFileSync(newPage, 'utf8')
  assert.ok(html.includes('only-on-the-site.js?v=4'), 'asset lines from the sibling post')
  assert.ok(html.includes('<h1 class="article-title">Fresh post</h1>'))
  assert.match(bodyOf(html), /Brand new text\./)

  await until(
    () => /blog_html: \.\.\/site\/thought-cloud\/fresh-post\/index\.html/.test(t.readFile('blog/fresh.md')),
    'pairing written into the note'
  )
  assert.ok(t.readFile('blog/fresh.md').endsWith('---\n\n# Fresh post\n\nBrand new text.\n'), 'note text untouched')
  const state = await until(blogPost, 'fresh note paired after reload')
  assert.equal(state.htmlPath, newPage)
  assert.equal(state.held, false)

  await appendToParagraph('Brand new text.', ' Edited.')
  await save()
  await until(async () => (await blogPost()).revision === 1, 'new page written on save')
  assert.match(bodyOf(fs.readFileSync(newPage, 'utf8')), /Brand new text\. Edited\./)
})

test('an iframe keeps its data-max-height in the page', async () => {
  // The site's embed-resize.js caps a self-sizing iframe by this attribute.
  await openNote('blog/paired.md')
  const note = path.join(t.workspace, 'blog/paired.md')
  const embed = '<iframe src="report/index.html" width="800" height="700" data-max-height="80vh" frameborder="0" loading="lazy"></iframe>'
  fs.writeFileSync(note, `${fs.readFileSync(note, 'utf8')}\n${embed}\n`)
  // The tab reloads from disk; then write the page from the note as it now is.
  await until(
    () => t.store('editor', (s) => s.currentFile.markdown.includes('data-max-height')),
    'note reloaded with the iframe'
  )
  const before = (await blogPost()).revision
  await t.store('editor', (s) => { s.BLOG_POST_SYNC(s.currentFile.id, 'overwrite') })
  await until(async () => (await blogPost()).revision > before, 'page written')
  assert.match(bodyOf(readPage()), /<iframe [^>]*data-max-height="80vh"/)
})

test('no renderer errors', () => {
  assert.deepEqual(t.errors(), [])
})
